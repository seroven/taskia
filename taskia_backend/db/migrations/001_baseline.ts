async function ensureMembership(client: Client, troopId: number, userId: number, role: string) {
  const activeElsewhere = await client.query(
    `SELECT id, troop_id FROM troop_members
     WHERE user_id = $1 AND left_at IS NULL AND troop_id <> $2
     LIMIT 1`,
    [userId, troopId],
  )
  if (activeElsewhere.rows[0]) return

  const existing = await client.query(
    `SELECT id, left_at, role FROM troop_members
     WHERE troop_id = $1 AND user_id = $2 LIMIT 1`,
    [troopId, userId],
  )
  if (existing.rows[0]) {
    if (existing.rows[0].left_at != null) {
      await client.query(
        `UPDATE troop_members SET left_at = NULL, role = $1, joined_at = NOW() WHERE id = $2`,
        [role, existing.rows[0].id],
      )
    } else if (existing.rows[0].role !== role) {
      await client.query(`UPDATE troop_members SET role = $1 WHERE id = $2`, [
        role,
        existing.rows[0].id,
      ])
    }
    return
  }
  await client.query(
    `INSERT INTO troop_members (troop_id, user_id, role) VALUES ($1, $2, $3)`,
    [troopId, userId, role],
  )
}

