async function seedDemoTroops(client: Client, passwordHash: string) {
  const anchor = await client.query(
    `SELECT id FROM troops WHERE name = $1 AND is_active = TRUE LIMIT 1`,
    [ANCHOR_TROOP],
  )
  const already =
    anchor.rows[0] != null &&
    (
      await client.query(
        `SELECT COUNT(*)::int AS c FROM troop_members
         WHERE troop_id = $1 AND left_at IS NULL`,
        [Number(anchor.rows[0].id)],
      )
    ).rows[0].c >= 5

  if (already) {
    console.log(`  seed tropas demo: "${ANCHOR_TROOP}" ya tiene miembros — omito`)
    return
  }

  const weekStart = weekStartMondayLima()
  let seedKey = 1
  for (const troop of TROOPS) {
    const existingTroop = await client.query(`SELECT id FROM troops WHERE name = $1 LIMIT 1`, [
      troop.name,
    ])
    let troopId: number
    if (existingTroop.rows[0]) {
      troopId = Number(existingTroop.rows[0].id)
      await client.query(
        `UPDATE troops
         SET is_active = TRUE, planet_style_id = $2, planet_seed = $3
         WHERE id = $1`,
        [troopId, troop.planet_style_id, troop.planet_seed],
      )
    } else {
      const ins = await client.query(
        `INSERT INTO troops (name, planet_style_id, planet_seed)
         VALUES ($1, $2, $3) RETURNING id`,
        [troop.name, troop.planet_style_id, troop.planet_seed],
      )
      troopId = Number(ins.rows[0].id)
    }

    for (const member of troop.members) {
      const xpTotal = (member.level - 1) * 1000 + member.xpInto
      const explorerId = await ensureUser(
        client,
        member.username,
        `${member.username.toLowerCase()}@taskia.local`,
        'user',
        passwordHash,
        member.level,
        xpTotal,
      )
      await ensureCourses(client, explorerId)
      await ensureMembership(client, troopId, explorerId, member.role)
      await ensureWeekAward(client, explorerId, member.xpWeek, weekStart, seedKey)
      seedKey += 1

      const guardianName = GUARDIAN_BY_EXPLORER[member.username]
      if (guardianName) {
        const guardianId = await ensureUser(
          client,
          guardianName,
          `${guardianName.toLowerCase()}@taskia.local`,
          'parent',
          passwordHash,
          1,
          0,
        )
        await ensureLink(client, guardianId, explorerId)
      }
    }
  }
  console.log(`  seed tropas demo listas; password ${DEMO_PASSWORD}; week_start=${weekStart}`)
}

