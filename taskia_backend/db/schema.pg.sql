-- Vigila, al cerrar la transacción, que ninguna misión activa
-- cuelgue de un mundo o de un vínculo mundo-materia inactivo.
CREATE OR REPLACE FUNCTION assert_active_mission_link()
RETURNS TRIGGER AS $$
BEGIN
  IF TG_TABLE_NAME = 'study_missions' THEN
    IF NEW.is_active AND NOT EXISTS (
      SELECT 1
      FROM study_worlds w
      INNER JOIN study_world_courses wc
        ON wc.world_id = w.id AND wc.course_id = NEW.course_id
      WHERE w.id = NEW.world_id
        AND w.is_active
        AND wc.is_active
    ) THEN
      RAISE EXCEPTION 'Hay una misión activa en un mundo o materia inactiva';
    END IF;
  ELSIF TG_TABLE_NAME = 'study_worlds' THEN
    IF NOT NEW.is_active AND EXISTS (
      SELECT 1 FROM study_missions m
      WHERE m.world_id = NEW.id AND m.is_active
    ) THEN
      RAISE EXCEPTION 'Hay una misión activa en un mundo o materia inactiva';
    END IF;
  ELSIF TG_TABLE_NAME = 'study_world_courses' THEN
    IF NOT NEW.is_active AND EXISTS (
      SELECT 1 FROM study_missions m
      WHERE m.world_id = NEW.world_id
        AND m.course_id = NEW.course_id
        AND m.is_active
    ) THEN
      RAISE EXCEPTION 'Hay una misión activa en un mundo o materia inactiva';
    END IF;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

