CREATE TABLE IF NOT EXISTS study_challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  world_id BIGINT NOT NULL REFERENCES study_worlds (id) ON DELETE CASCADE,
  scope TEXT NOT NULL,
  mission_id BIGINT NULL REFERENCES study_missions (id) ON DELETE SET NULL,
  course_id BIGINT NULL REFERENCES courses (id) ON DELETE SET NULL,
  difficulty TEXT NOT NULL CHECK (difficulty IN ('warm', 'quest', 'boss')),
  question_count INT NOT NULL,
  status TEXT NOT NULL DEFAULT 'in_progress'
    CHECK (status IN ('in_progress', 'completed', 'abandoned')),
  score SMALLINT NULL CHECK (score IS NULL OR (score >= 0 AND score <= 100)),
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  completed_at TIMESTAMPTZ NULL,
  CONSTRAINT ck_study_challenges_scope CHECK (
    (scope = 'mission' AND mission_id IS NOT NULL)
    OR (scope = 'course' AND course_id IS NOT NULL AND mission_id IS NULL)
    OR (scope = 'world' AND mission_id IS NULL AND course_id IS NULL)
  ),
  CONSTRAINT fk_study_challenges_world_owner
    FOREIGN KEY (world_id, user_id) REFERENCES study_worlds (id, user_id) ON DELETE CASCADE,
  CONSTRAINT fk_study_challenges_mission_world
    FOREIGN KEY (mission_id, world_id) REFERENCES study_missions (id, world_id)
    DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT fk_study_challenges_world_course
    FOREIGN KEY (world_id, course_id) REFERENCES study_world_courses (world_id, course_id)
    DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX IF NOT EXISTS idx_study_challenges_user ON study_challenges (user_id, started_at);
